// Views return markup only. Event handlers and saved state stay with the coordinator.
// Join fragments without adding whitespace to button labels or teaching text.
export function renderHomeView(progress) {
  return [
    `<section class="hero">`,
    `<div>`,
    `<span class="eyebrow">A LITTLE PLAY. A LOT OF POSSIBILITY.</span>`,
    `<h1>Hello, little<br>`,
    `<em>word explorer.</em>`,
    `</h1>`,
    `<p>Letters become sounds. Sounds become words.<br>Let’s discover them together with Bertie.</p>`,
    `<button class="primary" data-mode="random" aria-label="Play a random activity">`,
    `${icon('play')}`,
    `<span>Let’s play</span>`,
    `</button>`,
    `</div>`,
    `<div class="hero-art">`,
    `${renderRobot()}`,
    `<span class="orbit">Aa</span>`,
    `<span class="orbit two">B</span>`,
    `<span class="orbit three">✦</span>`,
    `</div>`,
    `</section>`,
    `<div class="section-heading">`,
    `<h2>Pick a little adventure</h2>`,
    `<span>16 ways to learn & play</span>`,
    `</div>`,
    `<section class="activities" aria-label="Learning activities">`,
    `${ACTIVITIES.map((a, i) =>
      [
        `<button class="activity-card" data-mode="`,
        `${a.id}`,
        `">`,
        `<span class="card-number `,
        `${progress.played[a.id] ? 'done' : ''}`,
        `">`,
        `${progress.played[a.id] ? '★' : String(i + 1).padStart(2, '0')}`,
        `</span>`,
        `<span class="activity-icon">`,
        `${activityIcon(a.id)}`,
        `</span>`,
        `<strong>`,
        `${a.title}`,
        `</strong>`,
        `<small>`,
        `${a.subtitle}`,
        `</small>`,
        `</button>`,
      ].join(''),
    ).join('')}`,
    `</section>`,
    `<div class="home-note">`,
    `<span style="font-size:28px">✦</span>`,
    `<span>`,
    `<b>Every little discovery counts.</b>`,
    `<br>No rush, no scores to beat. Just a friendly voice and room to grow.</span>`,
    `</div>`,
  ].join('');
}

